"""Write generated pages into uproduction-astro and open a DRAFT PR (never auto-merged)."""
import subprocess
from pathlib import Path
import aeo_generate
import aeo_guards
import aeo_policy
import re
import held_pages


def page_path(repo, page):
    return f"{repo}/src/content/{page['collection']}/{page['lang']}/{page['slug']}.md"


def write_pages(repo, pages):
    written = []
    for page in pages:
        path = Path(page_path(repo, page))
        path.parent.mkdir(parents=True, exist_ok=True)
        md = aeo_generate.to_markdown(page["frontmatter"], page["body"])
        path.write_text(md, encoding="utf-8")
        written.append(str(path.relative_to(repo)))
    return written


SITE_FACTS = "scripts/check-canonical-facts.mjs"
_FINDING_LINE = re.compile(r"^\s+(\S.*?):(\d+)\s*$")


def site_canonical_facts(repo, files, runner=subprocess.run):
    """Run the website's own canonical-facts guard (single source of truth) on the
    committed wave. On the site, founded-2010 / company-age / founding-phrasing hits are
    warnings; for generated files ANY finding (error or warning) blocks publication."""
    if not (Path(repo) / SITE_FACTS).is_file():
        raise RuntimeError(f"{SITE_FACTS} is missing in the destination repo; refusing to publish")
    res = runner(["node", SITE_FACTS, "--changed-since", "origin/master"], cwd=repo, text=True,
                 stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    out = getattr(res, "stdout", "") or ""
    hits = [ln.strip() for ln in out.splitlines()
            if (m := _FINDING_LINE.match(ln)) and m.group(1) in set(files)]
    if getattr(res, "returncode", 0) or hits:
        raise ValueError("site canonical-facts guard rejected the wave: "
                         + (", ".join(hits) or out.strip()[-300:]))


def publish(repo, pages, branch, date, runner=subprocess.run, dry_run=False):
    vetoed = set(held_pages.load().get("vetoed", []))
    for page in pages:
        if page["slug"] in vetoed:
            raise ValueError(f"vetoed page cannot publish: {page['slug']}")
        markdown = aeo_generate.to_markdown(page["frontmatter"], page["body"])
        violations = aeo_guards.destination_violations(markdown)
        if violations:
            raise ValueError(f"destination guard rejected {page['slug']}: {violations}")
        # Fail closed: never open a PR with a cut-off page or non-canonical facts.
        blocking = [v for v in (aeo_guards.check_content(markdown)
                                + aeo_guards.completeness_violations(
                                    page["body"], page["frontmatter"].get("faqs"))
                                + aeo_policy.page_violations(page["frontmatter"], page["body"]))
                    if aeo_guards.is_blocking(v)]
        if blocking:
            raise ValueError(f"completeness/canon guard rejected {page['slug']}: {blocking}")
    files = write_pages(repo, pages)
    if dry_run:
        return {"branch": branch, "files": files, "pr_url": None, "dry_run": True}

    def run(cmd, capture=False):
        result = runner(cmd, cwd=repo, text=True,
                        stdout=(subprocess.PIPE if capture else None),
                        stderr=(subprocess.STDOUT if capture else None))
        if getattr(result, "returncode", 0):
            raise RuntimeError(f"AEO publish command failed ({result.returncode}): {' '.join(cmd[:3])}")
        return result

    guard = Path(repo) / "scripts/check-competitor-names.mjs"
    if not guard.is_file():
        raise RuntimeError("Destination competitor guard is missing; refusing to publish")
    run(["node", "scripts/check-competitor-names.mjs"])
    run(["git", "checkout", "-B", branch])
    run(["git", "add", *files])
    run(["git", "commit", "-m", f"feat(aeo): GEO content {date} ({len(files)} pages)"])
    site_canonical_facts(repo, files, runner)   # before anything leaves the runner
    run(["git", "push", "-u", "origin", branch, "--force-with-lease"])
    title = f"AEO content {date}: {len(files)} pages"
    # Draft + marker: pr-checks' marker guard keeps CI red until AEO and Alon review it.
    body = ("Auto-generated by the weekly AEO/GEO loop. Do not merge: needs AEO review and "
            "Alon's approval. Generated FAQs are excludeFromSchema: true until AEO reviews them.")
    res = run(["gh", "pr", "create", "--draft", "--title", title, "--body", body, "--head", branch],
              capture=True)
    pr_url = (res.stdout or "").strip().splitlines()[-1] if getattr(res, "stdout", "") else None
    return {"branch": branch, "files": files, "pr_url": pr_url, "dry_run": False}
