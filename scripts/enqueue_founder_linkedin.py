def build_rows():
    rows = []
    for day, date, caption in POSTS:
        assert "—" not in caption, f"em-dash in day {day}"  # hard rule
        rows.append({
            "day": day,
            "network": "linkedin",
            "account": "li_personal",   # Alon's personal profile (HE)
            "lang": "he",
            "headline": f"Founder post {day}",
            "caption": caption,
            "scheduled_date": date,
        })
    return rows


def main():
    go = "--go" in sys.argv
    rows = build_rows()
    print(f"{'GO - inserting' if go else 'DRY-RUN'} {len(rows)} founder LinkedIn posts (li_personal):\n")
    for r in rows:
        print(f"  day {r['day']} @ {r['scheduled_date']}  ::  {r['caption'].splitlines()[0][:58]}")
    if not go:
        print("\n(dry-run) re-run with --go to enqueue as PENDING for the approve-gate.")
        return
    fresh = [r for r in rows if not queue.day_enqueued(r["day"], r["scheduled_date"])]
    if not fresh:
        print("\nAll 6 already enqueued - nothing to do.")
        return
    queue.insert_rows(fresh)
    print(f"\nOK enqueued {len(fresh)} PENDING rows. They appear in the daily approve-gate email.")


if __name__ == "__main__":
    main()
